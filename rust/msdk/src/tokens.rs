//! Design tokens shared by the SDK runtime and the compositor (`data/tokens.json`).
//!
//! Colours are deliberately absent: apps use the theme's foreground, background, accent and semantic colours so dark mode,
//! accent choice and contrast follow the user's settings. Values are logical pixels.

use serde_json::Value;

const RAW: &str = include_str!("../data/tokens.json");

pub fn tokens() -> Value {
    serde_json::from_str(RAW).expect("tokens.json is valid")
}

fn num(path: &[&str]) -> f64 {
    let mut v = tokens();
    for p in path {
        v = v[*p].clone();
    }
    v.as_f64().unwrap_or(0.0)
}

/// Pixels for a `spacing` enum value (`small`, `medium`, `large`).
pub fn spacing_px(name: &str) -> i32 {
    num(&["spacing", name]) as i32
}

/// GTK CSS for the SDK classes (`msdk-*`). Scoped to the app; no colours except theme references.
pub fn css() -> String {
    let t = tokens();
    let r = |k: &str| t["radius"][k].as_i64().unwrap_or(0);
    let ts = |k: &str| t["type_scale"][k].as_f64().unwrap_or(1.0);
    let w = &t["window"];
    format!(
        "/* generated by `msdk tokens`; do not edit */\n\
         window.csd decoration, window.csd.unified decoration {{ box-shadow: 0 0 0 {px}px alpha(black, {a}); margin: 0; }}\n\
         window.csd:backdrop decoration {{ box-shadow: 0 0 0 {px}px alpha(black, {ab}); }}\n\
         .msdk-title {{ font-size: {title}em; font-weight: 600; }}\n\
         .msdk-heading {{ font-size: {heading}em; font-weight: 600; }}\n\
         .msdk-body {{ font-size: {body}em; }}\n\
         .msdk-caption {{ font-size: {caption}em; opacity: 0.75; }}\n\
         .msdk-muted {{ opacity: 0.65; }}\n\
         .msdk-card {{ background: alpha(currentColor, {sa}); border-radius: {card}px; padding: {pad}px; }}\n\
         .msdk-control {{ border-radius: {control}px; min-height: 40px; }}\n\
         .msdk-error {{ color: @error_color; }}\n\
         .msdk-indicator {{ min-width: 18px; min-height: 3px; border-radius: 2px; background: alpha(currentColor, 0.45); }}\n\
         .msdk-indicator.focused {{ background: @accent_color; }}\n\
         .msdk-badge {{ background: @error_color; color: white; border-radius: 9px; padding: 0 5px; font-size: {caption}em; }}\n",
        px = w["outline_px"].as_i64().unwrap_or(1),
        a = w["outline_alpha"].as_f64().unwrap_or(0.28),
        ab = w["outline_alpha_backdrop"].as_f64().unwrap_or(0.18),
        title = ts("title"),
        heading = ts("heading"),
        body = ts("body"),
        caption = ts("caption"),
        sa = t["surface_alpha"].as_f64().unwrap_or(0.06),
        card = r("card"),
        control = r("control"),
        pad = spacing_px("medium"),
    )
}
