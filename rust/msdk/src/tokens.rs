//! Design tokens shared by the SDK runtime and the compositor (`data/tokens.json`).
//!
//! Colours are deliberately absent: apps use the theme's foreground, background, accent and semantic colours so dark mode,
//! accent choice and contrast follow the user's settings. Values are logical pixels.

use serde_json::Value;

const RAW: &str = include_str!("../data/tokens.json");

pub fn tokens() -> Value {
    serde_json::from_str(RAW).expect("tokens.json is valid")
}

fn num(path: &[&str]) -> f64 {
    let mut v = tokens();
    for p in path {
        v = v[*p].clone();
    }
    v.as_f64().unwrap_or(0.0)
}

/// Pixels for a `spacing` enum value (`small`, `medium`, `large`).
pub fn spacing_px(name: &str) -> i32 {
    num(&["spacing", name]) as i32
}

