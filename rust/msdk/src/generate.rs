//! Inspectable Rust models and standalone GTK projects from checked descriptions.
//! Generation never executes app services or installs anything.

use std::collections::BTreeMap;
use std::path::Path;

use serde_json::Value;

fn literal(value: &str) -> String {
    format!("{value:?}")
}

// Preserve ordinary names, including Rust keywords, and encode the few names
// Rust cannot represent as raw identifiers. The prefix is reserved by encoding
// user names beginning with it too, so distinct source names cannot collide.
fn ident(name: &str) -> String {
    if !name.is_empty()
        && name != "_"
        && !matches!(name, "self" | "Self" | "super" | "crate")
        && !name.starts_with("msdk_encoded_")
        && !name.as_bytes()[0].is_ascii_digit()
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
    {
        format!("r#{name}")
    } else {
        format!("msdk_encoded_{}", name.as_bytes().iter().map(|b| format!("{b:02x}")).collect::<String>())
    }
}

fn rust_type(ty: &str) -> Result<String, String> {
    Ok(match ty {
        "text" => "String".into(),
        "bool" => "bool".into(),
        "number" => "serde_json::Number".into(),
        t if t.starts_with("list<") && t.ends_with('>') => {
            format!("Vec<records::{}>", ident(&t[5..t.len() - 1]))
        }
        other => return Err(format!("gen: unsupported type {other:?}")),
    })
}

fn checked(doc: &Value) -> Result<(), String> {
    let errors: Vec<_> =
        crate::check(doc).into_iter().filter(|d| d.severity == crate::Severity::Error).map(|d| d.to_string()).collect();
    if errors.is_empty() { Ok(()) } else { Err(errors.join("\n")) }
}

/// Generate typed records, State and Message, with lossless JSON/event bridges.
/// Number uses serde_json::Number rather than rounding integer observations to f64.
pub fn models(doc: &Value) -> Result<String, String> {
    checked(doc)?;
    let mut out = String::from(
        "// Generated by msdk gen. Edit the description and regenerate in a new directory.\n\
         #![allow(non_snake_case, non_camel_case_types)]\n\
         pub mod records {\n",
    );
    for (name, fields) in doc["types"].as_object().into_iter().flatten() {
        out.push_str(&format!(
            "    #[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n    pub struct {} {{\n",
            ident(name)
        ));
        for (name, ty) in fields.as_object().into_iter().flatten() {
            let ty = rust_type(ty.as_str().ok_or("gen: field type must be a string")?)?;
            out.push_str(&format!(
                "        #[serde(rename = {})]\n        pub {}: {ty},\n",
                literal(name),
                ident(name)
            ));
        }
        out.push_str("    }\n");
    }
    out.push_str("}\n#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\npub struct State {\n");
    for (name, ty) in doc["state"].as_object().into_iter().flatten() {
        let ty = rust_type(ty.as_str().ok_or("gen: state type must be a string")?)?;
        out.push_str(&format!("    #[serde(rename = {})]\n    pub {}: {ty},\n", literal(name), ident(name)));
    }
    out.push_str("}\nimpl State {\n    pub fn initial() -> Result<Self, serde_json::Error> {\n        Self::from_store(msdk::logic::initial_store(&document()))\n    }\n    pub fn from_store(store: msdk::logic::Store) -> Result<Self, serde_json::Error> {\n        serde_json::from_value(serde_json::Value::Object(store))\n    }\n    pub fn into_store(self) -> Result<msdk::logic::Store, serde_json::Error> {\n        match serde_json::to_value(self)? {\n            serde_json::Value::Object(store) => Ok(store),\n            _ => unreachable!(\"State serializes as an object\"),\n        }\n    }\n}\n#[derive(Debug, Clone, PartialEq)]\npub enum Message {\n");
    for (name, ty) in doc["messages"].as_object().into_iter().flatten() {
        let payload = if ty == "none" {
            String::new()
        } else {
            format!("({})", rust_type(ty.as_str().ok_or("gen: message type must be a string")?)?)
        };
        out.push_str(&format!("    {}{payload},\n", ident(name)));
    }
    out.push_str("}\nimpl Message {\n    pub fn into_event(self) -> (String, Option<serde_json::Value>) {\n        match self {\n");
    for (name, ty) in doc["messages"].as_object().into_iter().flatten() {
        let (pat, payload): (String, String) = if ty == "none" {
            (String::new(), "None".into())
        } else {
            ("(value)".into(), "Some(serde_json::json!(value))".into())
        };
        out.push_str(&format!("            Self::{}{pat} => ({}.into(), {payload}),\n", ident(name), literal(name)));
    }
    out.push_str("        }\n    }\n}\n\n/// The checked description embedded in this application.\npub fn document() -> serde_json::Value {\n    serde_json::from_str(include_str!(\"../app.ui.json\")).expect(\"generated checked description\")\n}\n");
    Ok(out)
}

/// Return a complete standalone Cargo project without mutating the filesystem.
/// Custom service manifests are not silently invented or replaced by fixtures.
pub fn project(doc: &Value, sdk_root: &Path) -> Result<BTreeMap<String, String>, String> {
    project_with_manifests(doc, sdk_root, &[])
}

pub fn project_with_manifests(
    doc: &Value,
    sdk_root: &Path,
    manifests: &[Value],
) -> Result<BTreeMap<String, String>, String> {
    for manifest in manifests {
        crate::vocab::load_manifest(manifest)?;
    }
    checked(doc)?;
    if doc["logic"] == "rust" {
        return Err(
            "gen: Rust logic must be supplied by the app; use models() and Host::open_with with a LogicFactory".into(),
        );
    }
    let root = sdk_root.canonicalize().map_err(|e| format!("gen: SDK root: {e}"))?;
    for name in ["msdk", "msdk-gtk"] {
        if !root.join(name).join("Cargo.toml").is_file() {
            return Err(format!("gen: SDK root must contain {name}/Cargo.toml"));
        }
    }
    let surfaces = doc["surfaces"].as_object().ok_or("gen: missing surfaces")?;
    let surface =
        if surfaces.contains_key("main") { "main" } else { surfaces.keys().next().ok_or("gen: no surface")? };
    let id = doc["app"]["id"].as_str().ok_or("gen: missing app id")?;
    let package = format!("msdk-{}", id.rsplit('.').next().unwrap_or("app").replace('_', "-").to_ascii_lowercase());
    let root_text = root.to_str().ok_or("gen: SDK root must be UTF-8")?;
    let mut files = BTreeMap::new();
    files.insert("assets/icon.svg".into(), crate::package::DEFAULT_ICON.into());
    files.insert("LICENSE".into(), include_str!("../LICENSE").into());
    files.insert("Cargo.toml".into(), format!(
        "[package]\nname = {package:?}\nversion = \"0.1.0\"\nlicense = \"GPL-3.0-only\"\nedition = \"2024\"\npublish = false\n\n[workspace]\n\n[lib]\nname = \"app_model\"\n\n[dependencies]\nmsdk = {{ path = {} }}\nmsdk-gtk = {{ path = {} }}\ngtk = {{ package = \"gtk4\", version = \"0.11\", features = [\"v4_20\"] }}\nserde = {{ version = \"1\", features = [\"derive\"] }}\nserde_json = \"1\"\n",
        serde_json::to_string(&format!("{root_text}/msdk")).unwrap(),
        serde_json::to_string(&format!("{root_text}/msdk-gtk")).unwrap(),
    ));
    files.insert("app.ui.json".into(), serde_json::to_string_pretty(doc).map_err(|e| e.to_string())? + "\n");
    let mut model = models(doc)?;
    let mut registration = String::new();
    for (index, manifest) in manifests.iter().enumerate() {
        let manifest = serde_json::to_string(manifest).map_err(|e| e.to_string())?;
        files.insert(format!("app-{index}.services.json"), manifest.clone());
        registration.push_str(&format!("    msdk::vocab::load_manifest(&serde_json::from_str({}).expect(\"embedded service manifest\")).expect(\"checked service manifest\");\n", literal(&manifest)));
    }
    model = model.replace(
        "pub fn document() -> serde_json::Value {\n",
        &format!("pub fn document() -> serde_json::Value {{\n    static REGISTER: std::sync::OnceLock<()> = std::sync::OnceLock::new();\n    REGISTER.get_or_init(|| {{\n{registration}    }});\n"),
    );
    files.insert("src/lib.rs".into(), model);
    files.insert(
        "src/main.rs".into(),
        include_str!("../templates/project/main.rs")
            .replace("@APP_ID@", &literal(id))
            .replace("@SURFACE@", &literal(surface)),
    );
    files.insert("README.md".into(), format!(
        "# {}\n\nGenerated by `msdk gen`; SDK format {}.\n\nOn a supported Linux GTK 4.20+ development host, with Rust 2024, pkg-config,\nGTK development headers, Wayland development headers and wayland-scanner installed:\n\n```sh\ncargo build\ncargo test\ncargo run\n```\n\n`src/lib.rs` exposes typed records, `State`, `Message::into_event` and the embedded\ndescription. Edit `app.ui.json` for views/rules, or use a new output directory to\nregenerate models after changing types. Keep the SDK checkout at `{root_text}`;\nthe generated project uses explicit local dependencies and its own Cargo workspace.\n\nThe executable runs the real GTK Host with the description's update rules and\nbuilt-in services. Custom services/feeds require an app-local `Services` adapter\nand `Host::open_with`; generation does not implement those backends. Panel\nplacement requires the documented Pantheon shell protocol and target-host tests.\nBuild/launch success is separate from visual, accessibility, service, packaging\nand installed desktop acceptance. No install or background service is performed\nby generation.\n",
        doc["app"]["name"].as_str().unwrap_or("SDK app"), crate::FORMAT_VERSION,
    ));
    files.insert("tests/model.rs".into(), "#[test]\nfn initial_state_round_trips() {\n    let state = app_model::State::initial().expect(\"typed initial state\");\n    let store = state.clone().into_store().unwrap();\n    assert_eq!(app_model::State::from_store(store).unwrap(), state);\n}\n".into());
    Ok(files)
}

/// Creates a new directory exclusively; existing projects are never overwritten.
pub fn write_project(dir: &Path, files: &BTreeMap<String, String>) -> Result<(), String> {
    std::fs::create_dir(dir).map_err(|e| format!("gen: {}: {e}", dir.display()))?;
    for (name, body) in files {
        let path = dir.join(name);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        }
        std::fs::write(path, body).map_err(|e| e.to_string())?;
    }
    Ok(())
}
